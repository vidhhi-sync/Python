#Operators

#Arithmetic operators
d = 4
e = 2
print(d+e)
print(d-e)
print(d*e)
print(d/e)
print(d**e)
print(d%e)

#Relational Operators
f = 3
g = 6
print(f==g)
print(f!=g)
print(f>g)
print(f<g)

#Assignment Operators
num = 100
num+=10 #means num = num + 10, which is 100 + 10
print(num)
num-=10
print(num)
num*=1
print(num)
num/=10
print(num)
num%=10
print(num)
num**=2
print(num)

#Logical Operators
print(not False)
